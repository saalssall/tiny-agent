PLACEHOLDER = re.compile(r"\{(\w+)\}")


def expand(template: str, rng: random.Random) -> list[str]:
    """Return up to FILLINGS_PER_TEMPLATE distinct commands for a template."""
    names = PLACEHOLDER.findall(template)
    if not names:
        return [template.replace("{{", "{").replace("}}", "}")]
    seen: set[str] = set()
    for _ in range(FILLINGS_PER_TEMPLATE * 4):  # a few extra tries to find distinct fillings
        values = {name: rng.choice(FILLERS[name]) for name in names}
        command = template.replace("{{", "\x00").replace("}}", "\x01")
        for name, value in values.items():
            command = command.replace("{" + name + "}", value)
        seen.add(command.replace("\x00", "{").replace("\x01", "}"))
        if len(seen) >= FILLINGS_PER_TEMPLATE:
            break
    return sorted(seen)


def main() -> None:
    rng = random.Random(0)
    rows: list[tuple[str, str, int]] = []
    template_id = 0
    for label, templates in (("safe", SAFE_TEMPLATES), ("risky", RISKY_TEMPLATES)):
        for template in templates:
            template_id += 1
            for command in expand(template, rng):
                rows.append((command, label, template_id))

    with OUT.open("w", newline="") as fh:
        writer = csv.writer(fh)
        writer.writerow(["command", "label", "template"])
        writer.writerows(rows)

    n_safe = sum(1 for r in rows if r[1] == "safe")
    print(
        f"wrote {len(rows)} commands ({n_safe} safe, {len(rows) - n_safe} risky) "
        f"from {template_id} templates to {OUT.name}"
    )


if __name__ == "__main__":
    main()
